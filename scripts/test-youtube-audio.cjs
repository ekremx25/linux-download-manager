const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
let handler,track={id:'tr.4'}, wrapped=null;
const replies=[];
const window={addEventListener:(_,fn)=>handler=fn,postMessage:p=>replies.push(p)};
const context={window,location:{origin:'https://www.youtube.com',href:'https://www.youtube.com/watch?v=test'},URL,document:{querySelector:()=>wrapped,getElementById:()=>({getAudioTrack:()=>track})}};
vm.createContext(context);vm.runInContext(fs.readFileSync('browser/chromium/youtube-audio-observer.js','utf8'),context);
const request=()=>handler({source:window,origin:context.location.origin,data:{type:'ldm-audio-track-request',requestId:'test'}});
request();assert.equal(replies.at(-1).language,'tr');
track={languageCode:'en-US'};request();assert.equal(replies.at(-1).language,'en-us');
track={id:'tr.4][bad'};request();assert.equal(replies.at(-1).language,null);
track={getLanguageInfo:()=>({id:'tr',name:'Türkçe'})};request();assert.equal(replies.at(-1).language,'tr');
track={getLanguageInfo:()=>({code:'de'})};request();assert.equal(replies.at(-1).language,'de');
track={getLanguageInfo:()=>{throw Error('unavailable')},id:'fr.4'};request();assert.equal(replies.at(-1).language,'fr');
track=null;wrapped={player_:{getAudioTrack:()=>({getLanguageInfo:()=>({id:'ja'})})}};request();assert.equal(replies.at(-1).language,'ja');
wrapped=null;
track={id:'bad/code'};request();assert.equal(replies.at(-1).language,null);
track=null;request();assert.equal(replies.at(-1).language,null);
assert.equal(replies.at(-1).videoId,'test');
console.log('PASS: active audio selection follows language switches; unknown selection is not guessed');
